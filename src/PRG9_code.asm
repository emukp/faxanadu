;============================================================================
; Faxanadu (U).nes - zh_version
;
; PRG9 hand-written code - the full-width (Hanzi) text path.
;
; Entered from ZHV_FullWidthEntry in PRG15 (the fixed bank), which has already:
;   * read the pair's second byte out of the message stream while bank 13 was
;     mapped, storing it in ZHV_GlyphChar;
;   * saved the bank to return to in ZHV_CallerBank;
;   * mapped BANK_HANZI_TEXT (bank 9, i.e. this bank) into $8000-$BFFF and
;     jumped here.
;
; WHY BANK 9 AND NOT 16: the MMC1 only addresses banks 0-15 in $8000-$BFFF while
; 16 KiB PRG mode is selected (the PRG bank register's bit 4 is ignored), so the
; original plan's "font in PRG16" could never be switched in - writing $10
; selects bank 0, and the jump into this code landed in bank 0's data.  Bank 9 is
; the one bank the original game leaves entirely unused ($FF; DEFS calls it
; BANK_9_UNUSED).  See docs/hanhua-12x12.md, "MMC1 只能寻址 banks 0-15".
;
; So this code runs with its own bank already selected and must NOT switch banks:
; a switch here would change what $8000-$BFFF points at and the very next
; instruction would be fetched from the wrong bank.  The return path is the
; ZHV_FullWidthDone stub back in the fixed bank, for the same reason.
;
; Everything it needs lives in this bank - the 12x12 glyph table (generated by
; hanhua/font_gen.py, TILE_GLYPHS_HANZI) starts here and the writer reads
; it directly, so there is no nested bank switch in the drawing path.
;
; NOTE ON THE GLYPH TABLE: it must come FIRST in the memory area, i.e. before any
; code, because the writer addresses glyphs relative to its own bank base with
; `base + glyph_id*64`.  font_gen.py emits it into segment PRG9, and the linker
; places PRG9 (glyphs) before PRG9_CODE (this file).
;============================================================================

    .segment "PRG9_CODE"
    .reloc

;============================================================================
; Draw one full-width character.
;
; INPUTS (from ZHV_FullWidthEntry in PRG15):
;     stack:  the pair's second byte, pushed by the entry (it is popped here, so
;             nothing else may touch the stack first); below it sits the caller
;             bank, which ZHV_FullWidthDone pops after this routine returns
;
; Encoding: a full-width character is the two bytes `b1 b2` with b1 >= $80;
; b1 selects the glyph bank ($80 = bank 9) and b2 is the glyph index inside that
; bank's table (see below).  ASCII stays single-byte and never enters this
; routine - the hook in PRG15 sends anything below $80 to TextBox_WriteChar.
;
; The character occupies a 2x2 tile block:
;     page N   slots 2C and 2C+1  (top half)
;     page N+1 slots 2C and 2C+1  (bottom half)
; where N = $14 + 2*((DrawnLineNum + LineScrollOffset) & $01) - the two logical
; lines must land on separate PAIRS of the rolling four CHR pages, because one
; character is 2 tiles tall - and C = CharPosForLine.  A full-width character
; consumes two tile columns, so this routine adds one on the way out and
; TextBox_ShowMessage_HandleSpaceOrEndOfLine adds the other; without that, the
; next character's left tile would land on this one's right.
;============================================================================
.export ZHV_DrawFullWidthChar
ZHV_DrawFullWidthChar:
    LDA #$01                                ; DIAG
    STA ZHV_Trace

    ;
    ; A pending page turn (see ZHV_ScrollBox) is executed here, before this
    ; character is drawn into the freshly scrolled box.
    ;
    LDA a:TextBox_LineScrollOffset
    BPL @_no_pending_turn
    JSR ZHV_DoPendingTurn

  @_no_pending_turn:

    ;
    ; Glyph index.  The encoding is the J version's own idea, one byte wider:
    ;
    ;     b1 = $80 + font bank selector (only $80 / bank 9 exists for now)
    ;     b2 = glyph index 0..255 INTO that bank's table
    ;
    ; so the index is simply the byte the entry pushed - no subtraction and no
    ; codepoint -> index table.  hanhua/text/chars_zh.txt is the single
    ; source of truth for the order, and hanhua/script_codec.py is what
    ; turns text into these pairs (and back).  When the character set outgrows
    ; one bank, b1 selects the next glyph bank (see docs/hanhua-12x12.md, r5
    ; plan); it is deliberately not a Unicode lead byte any more.
    ;
    ; ASCII ($20-$7E) never reaches this routine: the hook sends anything below
    ; $80 to the original half-width writer, which is why mixed lines work.
    ;
    PLA                                     ; b2 = glyph index, low 8 bits
    STA ZHV_GlyphIndex
    LDA a:ZHV_GlyphChar                     ; b1, stashed by ZHV_FullWidthEntry
    AND #$7F
    STA a:ZHV_GlyphChar                     ; index bits 8-14 (0 for $80)
    LDA #$02                                ; DIAG
    STA ZHV_Trace

    ;
    ; Source address = TILE_GLYPHS_HANZI + index * 24.
    ;
    ; The table is PACKED (see PRG9.asm, generated by font_gen.py --packed):
    ; 12 rows of 2 bytes, big-endian, covering the 12x12 ink window of the cell,
    ; because a 32-byte glyph per character does not fit in one 16 KiB bank once
    ; the whole script is translated.  24 = 3 * 8, so the offset is built as
    ; (index * 3) << 3 - see the sequence below.
    ;
    ; The table is stored 1bpp (8 bytes per 8x8 tile, plane0 only) because the
    ; pixels are white-only anyway: the writer emits each 8-byte half TWICE, so
    ; plane1 = plane0 and the tile is colour 3 - the same trick the original
    ; half-width writer uses.  That halves the bank's cost per glyph, which is
    ; what lets one 16 KiB bank (bank 9) hold 512 glyphs instead of 256.
    ;
    ; A 16-bit shift is used (not the "+$80 bias" the half-width writer relies
    ; on) because the glyph table is not at $8000.
    ;
    LDA a:ZHV_GlyphIndex               ; index low
    STA Temp_Int24
    LDA a:ZHV_GlyphChar
    STA Temp_Int24_M                   ; index high (bits 8-14)
    ASL Temp_Int24                     ; index * 2 ...
    ROL Temp_Int24_M
    ASL Temp_Int24                     ; ... * 4 ...
    ROL Temp_Int24_M
    ASL Temp_Int24                     ; ... * 8 ...
    ROL Temp_Int24_M
    LDA Temp_Int24                     ; keep 8*index for the "+ x"
    STA a:ZHV_GlyphIndex
    LDA Temp_Int24_M
    STA a:ZHV_GlyphChar
    ASL Temp_Int24                     ; 16*index
    ROL Temp_Int24_M
    LDA Temp_Int24
    CLC
    ADC a:ZHV_GlyphIndex               ; + 8*index = 24*index
    STA Temp_Int24
    LDA Temp_Int24_M
    ADC a:ZHV_GlyphChar
    STA Temp_Int24_M
    LDA Temp_Int24
    CLC
    ADC #<TILE_GLYPHS_HANZI
    STA Temp_Int24
    LDA Temp_Int24_M
    ADC #>TILE_GLYPHS_HANZI
    STA Temp_Int24_M

    ;
    ; Compute the PPU target address (top-left slot of the 2x2 block).
    ;
    LDA #$00
    STA PPU_TargetAddr_U
    LDA a:TextBox_CharPosForLine            ; column
    ASL A                                   ; *16 = col * one tile (16 bytes);
    ASL A                                   ; CharPosForLine is a TILE column and
    ASL A                                   ; a full-width character has already
    ASL A                                   ; advanced it by 2, so the low byte
    STA PPU_TargetAddr                      ; lands on the character's left tile.
    ;
    ; Page: the two logical full-width lines must sit on two SEPARATE PAIRS of
    ; the rolling four CHR pages ($14/$15 and $16/$17), because one character is
    ; 2 tiles tall and would otherwise have its bottom half overwritten by the
    ; next line's top half.
    ;
    ; The box is a four-page CIRCULAR buffer: box row r displays CHR page
    ; $14 + ((r + LineScrollOffset) & $03), and the scroll (Fill4Lines) advances
    ; LineScrollOffset.  A full-width line must therefore be drawn into the page
    ; pair that starts at row 2*line:
    ;
    ;     page = $14 + ((2*DrawnLineNum + LineScrollOffset) & $03)
    ;
    ; which is why Fill4Lines now steps LineScrollOffset by TWO (one whole line).
    ; With the original +1 the pairs slipped by half a line on every scroll, and
    ; a character wrapped onto a new line landed in the other line's pages - that
    ; was the visible corruption R5 fixes.  The half-width writer in PRG15 uses
    ; the same formula now.  See the R5 notes in docs/hanhua-12x12.md.
    ;
    LDA a:TextBox_DrawnLineNum
    ASL A                                   ; line 0/1 -> page pair 0/2
    CLC
    ADC a:TextBox_LineScrollOffset          ; + the scroll rotation
    AND #$03                                ; cap to the four buffered pages
    ADC #$14                                ; first text CHR page
    STA PPU_TargetAddr_U

    ;
    ; Draw the four tiles.  This bank is already mapped - see the header comment.
    ;
    LDA #$03                                ; DIAG
    STA ZHV_Trace
    JSR ZHV_DrawFullWidthTiles
    LDA #$05                                ; DIAG
    STA ZHV_Trace

    ;
    ; A full-width character occupies two tile columns.
    ; TextBox_ShowMessage_HandleSpaceOrEndOfLine adds the first one; add the
    ; second here so the next character starts two columns along.
    ;
    INC a:TextBox_CharPosForLine

    ;
    ; Hand control back to the fixed bank, which owns the bank restore.
    ;
    JMP ZHV_FullWidthDone

;============================================================================
; Draw the 2x2 tile block at PPU_TargetAddr.
;
; The glyph is 64 bytes = 4 tiles, laid out in the table as
;     bytes  0..15  TL  (plane0 then plane1)
;     bytes 16..31  TR
;     bytes 32..47  BL
;     bytes 48..63  BR
; and each tile is written as 16 bytes: 8 of plane0 followed by the SAME 8
; bytes as plane1, which is the original engine's trick for white text
; (pixel value %11 = palette colour 3).
;
; PPUBuffer is a linear stream that PPUBuffer_Draw walks UPWARD from
; PPUBuffer_ReadOffset, and PPUBuffer_QueueCommandOrLength (which writes
; [length][addr hi][addr lo] and advances X) sets the convention: store at
; PPUBuffer,X, then INX.  These helpers follow it exactly, and their loops end on
; a byte count rather than on X reaching zero - a downward copy would eat the
; queue header it was just handed and, once X wrapped to $FF, scribble over the
; whole 256-byte buffer, which in turn can wedge PPUBuffer_WaitForCapacity (it
; spins until there is capacity) and hang the game.
;
; Y is the cursor inside the 32-byte (1bpp) glyph and is left where it stopped,
; so consecutive ZHV_WriteTileFromTemp calls walk TL, TR, BL, BR linearly.  The
; loop bound is Y's low 3 bits rather than a counter - the same trick the original
; TextBox_Write8BytesFromTemp uses: every call starts on a multiple of 8, so
; "stop when Y is aligned again" means "8 bytes written" without spending a
; register or a RAM byte.
;
; IN:  Temp_Int24 = glyph base, Y = source offset, X = PPUBuffer cursor
; OUT: X = cursor past the written bytes, Y = source offset past them
;============================================================================
ZHV_WriteZeroRun:
    ;
    ; Write `A` blank tile rows (2 PPU bytes each: plane0 and plane1).
    ;
    STA a:ZHV_GlyphIndex                    ; row counter (the glyph id is done)
    LDA #$00
  @_row:
    STA PPUBuffer,X
    INX
    DEC a:ZHV_GlyphIndex
    BNE @_row
    RTS


ZHV_WritePackedRows:
    ;
    ; Copy `A` packed rows into the PPU buffer as ONE plane: one byte per row, X
    ; advancing one byte per row.  Y steps by 2 because a row is a big-endian byte
    ; pair - even offsets are the left half of the 12-pixel row, odd offsets the
    ; right half.
    ;
    ; It writes a single plane on purpose.  A CHR tile is plane0[8] followed by
    ; plane1[8], NOT the two planes interleaved per row: writing "byte, byte" per
    ; row put the glyph's first four rows in plane0 and the last four in plane1,
    ; which showed up on screen as a half-height two-colour character.  The tile
    ; writer therefore runs this twice - once per plane.
    ;
    STA a:ZHV_GlyphIndex                    ; row counter
  @_row:
    LDA (Temp_Int24),Y
    STA PPUBuffer,X
    INX
    INY
    INY
    DEC a:ZHV_GlyphIndex
    BNE @_row
    RTS


ZHV_DrawFullWidthTiles:
    ;
    ; Unpack one 24-byte glyph into the four CHR slots of the 2x2 cell.
    ;
    ; The glyph sits FIVE ROWS HIGHER in the cell than the raw packing implies.
    ; font_gen.py stores the ink box as packed rows 0-11, which map to cell rows
    ; 4-15 - the baseline is cell row 13, so the ink occupied rows 5-15 and the
    ; character looked bottom-heavy (5 blank rows above it, none below).  The
    ; five-row nudge moves it to cell rows 0-10.
    ;
    ; That is the largest lossless shift: packed row 0 (cell row 4) is blank in
    ; all 582 glyphs (verified against src/PRG9.asm), and packed row 1 (which
    ; does carry ink) lands exactly on cell row 0.  Shifting six would clip the
    ; top row of 559 glyphs.
    ;
    ; The point of the nudge: the menu cursor's original offset (-32) puts the
    ; arrow level with cell row 0, which is where the 8x8 HUD-font menu strings
    ; start.  With the Hanzi raised, that same offset also centres the arrow on
    ; Chinese menus, so Menu_UpdateAndDraw keeps the cart's own value.
    ;
    ; So: TOP tiles (cell rows 0-7) are packed rows 1-8, and BOTTOM tiles (cell
    ; rows 8-15) are packed rows 9-11 followed by five blank rows.
    ;
    ; NOTE ON PPUBuffer_WriteOffset: PPUBuffer_QueueCommandOrLength does not
    ; continue from the X it is handed - it reloads X from PPUBuffer_WriteOffset
    ; every time (the original engine's routines each write ONE entry and publish
    ; the new cursor at the end, which is why that is safe there).  Writing four
    ; entries per character therefore has to publish the cursor before each
    ; re-queue, or all four headers land on top of each other and the PPU stream
    ; becomes garbage.
    ;
    LDY #$02                                ; packed offsets: 2,4,.. = rows 1-8
    ;
    ; --- top half: TL and TR, packed rows 1-8, each tile written as plane0 then
    ;     plane1 (both planes identical -> colour 3).  No blank rows up here any
    ;     more: the glyph has been nudged up into them.
    ;
    LDA #$10
    JSR PPUBuffer_QueueCommandOrLength
    LDY #$02
    LDA #$08
    JSR ZHV_WritePackedRows                 ; plane0: rows 1-8, left half
    LDY #$02
    LDA #$08
    JSR ZHV_WritePackedRows                 ; plane1

    STX PPUBuffer_WriteOffset
    LDA PPU_TargetAddr
    CLC
    ADC #$10
    STA PPU_TargetAddr                      ; next slot (TR)
    LDA #$10
    JSR PPUBuffer_QueueCommandOrLength
    LDY #$03                                ; odd offsets = right half
    LDA #$08
    JSR ZHV_WritePackedRows
    LDY #$03
    LDA #$08
    JSR ZHV_WritePackedRows

    ;
    ; --- bottom half: same two slots on the next CHR page, packed rows 9-11 then
    ;     five blank rows (the nudge pushed the glyph's bottom up to cell row 10).
    ;
    STX PPUBuffer_WriteOffset
    INC PPU_TargetAddr_U
    LDA PPU_TargetAddr
    SEC
    SBC #$10
    STA PPU_TargetAddr                      ; back to the first slot
    LDA #$10
    JSR PPUBuffer_QueueCommandOrLength
    LDY #$12                                ; offsets 18,20,22 = rows 9-11 left
    LDA #$03
    JSR ZHV_WritePackedRows                 ; plane0
    LDA #$05
    JSR ZHV_WriteZeroRun                    ; plane0: 5 blank rows
    LDY #$12
    LDA #$03
    JSR ZHV_WritePackedRows                 ; plane1
    LDA #$05
    JSR ZHV_WriteZeroRun                    ; plane1

    STX PPUBuffer_WriteOffset
    LDA PPU_TargetAddr
    CLC
    ADC #$10
    STA PPU_TargetAddr                      ; second slot
    LDA #$10
    JSR PPUBuffer_QueueCommandOrLength
    LDY #$13                                ; rows 9-11 right half
    LDA #$03
    JSR ZHV_WritePackedRows                 ; plane0
    LDA #$05
    JSR ZHV_WriteZeroRun
    LDY #$13
    LDA #$03
    JSR ZHV_WritePackedRows                 ; plane1
    LDA #$05
    JSR ZHV_WriteZeroRun

    STX PPUBuffer_WriteOffset
    RTS


;============================================================================
; zh_version: scroll the dialogue box up by one two-page line (the body of the
; original TextBox_ShowMessage_Fill4Lines, moved here from PRG15).
;
; WHY IT MOVED: PRG15 had two bytes left, and a two-line page turn needs one
; extra store (TextBox_MessagePaused).  Bank 9 has room, and everything this
; routine calls - PPU_SetAddrForTextBoxPos, TextBox_FillPlaceholderTextForLine*,
; PPUBuffer_WriteValueMany, PPU_IncrementAddrBy16 - lives in the FIXED bank, so
; a JSR from here works while bank 9 is mapped.  The caller is
; TextBox_ShowMessage_IncLineAndReset (a branch, so this routine's RTS returns to
; that routine's caller) and the return goes through ZHV_ScrollBoxDone in PRG15,
; which restores the bank: bank 9's code must not keep executing after a bank
; switch.
;
; The only behavioural change from the original body: see the page pause at the
; end.
;============================================================================
.export ZHV_ScrollBox
ZHV_ScrollBox:
    ;
    ; A FULL BOX IS A PAGE, AND A PAGE TURN WAITS FOR THE PLAYER.
    ;
    ; The engine calls this at every line end once the box is full.  Scrolling
    ; right away would push one of the two lines the player is still reading off
    ; the screen, so the scroll is DEFERRED: this only arms it (bit 7 of
    ; TextBox_LineScrollOffset) and, on every other line end, pauses - the down
    ; arrow appears, typing stops and A resumes the message
    ; (TextBox_CheckForDismiss -> TextBox_PrepareContinueMessage).  The next
    ; character drawn then calls ZHV_DoPendingTurn below and really scrolls.
    ;
    ; WHICH LINE ENDS PAUSE: TextBox_LineScrollOffset itself alternates 0/2 as the
    ; rotation advances (one page pair per scroll), so it IS the counter - no
    ; extra state is needed.  Pausing when it is 0 gives exactly two freshly
    ; A PAGE IS TWO LINES, AND A PAGE TURN CLEARS BOTH OF THEM.
    ;
    ; The engine reaches this at every line end while the box is full - that is,
    ; after the second line of a page.  It must wait for the player there, or the
    ; text would run on before the page could be read.
    ;
    ; PAUSING IS NOW UNCONDITIONAL (it used to alternate via the rotation): the
    ; turn below clears the box and starts the next page at the TOP line, so
    ; every wrap that finds the box full is a real page end.  The old
    ; "scroll one line" behaviour left the previous page's second line visible as
    ; the new page's first line, which is wrong the moment a page is only one
    ; line long (a 3-line message showed L2 twice: [L1 L2] then [L2 L3]).
    ;
    LDA a:TextBox_LineScrollOffset
    BMI ZHV_DoPendingTurn                   ; a turn is owed (we are resuming) -> do it
    ORA #$80                                ; else arm it for the next character
    STA a:TextBox_LineScrollOffset
    LDA #$ff
    STA a:TextBox_MessagePaused             ; wait for the player
  @_return:
    RTS


;============================================================================
; zh_version: perform a page turn that was armed while the player was reading.
;
; Entered from ZHV_DrawFullWidthChar (full-width text) and from the PRG15 stub
; TextBox_DoPendingPageTurn (half-width text).  Falls through into the scroll
; body, which is the original TextBox_ShowMessage_Fill4Lines.
;============================================================================
.export ZHV_DoPendingTurn
ZHV_DoPendingTurn:
    ;
    ; zh_version: a page turn BLANKS THE BOX, THEN THE NEXT PAGE TYPES FROM LINE 0.
    ;
    ; Two earlier attempts were wrong:
    ;   * rotating the four-page ring by one line (the classic scroll) left the
    ;     previous page's second line in place as the new page's first line;
    ;   * rotating twice (2 lines = a whole ring) did clear both, but the ring
    ;     re-pointing happens buffer-write by buffer-write, so the screen showed
    ;     the second line jumping up to the first before the blanking caught up;
    ;   * writing the blank placeholder per row only re-points NAMETABLE ids - it
    ;     does not touch CHR, so the old characters stayed and the new text was
    ;     typed straight over them (verified frame by frame).
    ;
    ; What actually empties the box is writing zeroes over its CHR: the four pages
    ; $14-$17 (1024 bytes) are the box's whole character area.  Doing that before
    ; any new character is drawn is what makes both lines disappear together.
    ; DrawnLineNum then goes back to 0 so the next page starts on the TOP line; a
    ; page with a single line therefore shows exactly that line.
    ;
    LDA a:TextBox_LineScrollOffset
    AND #$7f                                ; disarm; bits 0-1 are the rotation
    STA a:TextBox_LineScrollOffset
    ;
    ; The box's four "pages" ($14-$17) are CHR at PPU $1400-$17FF: its nametable
    ; ids are $40-$7F and the background uses pattern table 1, so id $40 is the
    ; pattern at $1000 + 64*16 = $1400.
    ;
    ; So: blank $1400-$17FF (four 256-byte pages).  PPUBuffer_WriteValueMany queues Y
    ; bytes into the PPU buffer and PPUBuffer_QueueCommandOrLength blocks until
    ; there is room, so this has to be done in buffer-sized chunks: asking for a
    ; whole 256-byte page in one call overruns the 256-byte buffer and hangs the
    ; game (measured).  16 bytes per call is what the engine itself uses.
    ;
    LDA #$14
    STA PPU_TargetAddr_U
    LDA #$00
    STA PPU_TargetAddr
    ; 64 x 16 bytes = 1024 bytes.  The counter lives in RAM, NOT in X:
    ; PPUBuffer_WriteValueMany ends with STX PPUBuffer_WriteOffset, so it clobbers
    ; X, and a DEX/BNE loop around it never terminates correctly (that is why an
    ; earlier version of this blanking appeared to do nothing at all).
    ;
    LDA #$40
    STA a:ZHV_GlyphIndex                    ; chunk counter (free until the glyph
  @_chunk:                                 ; index is fetched, after this turn)
    LDA #$00                                ; value: blank
    LDY #$10                                ; 16 bytes = one tile
    JSR PPUBuffer_WriteValueMany
    LDA PPU_TargetAddr                      ; advance the PPU target for the
    CLC                                     ; next chunk (the header re-sends it)
    ADC #$10
    STA PPU_TargetAddr
    BCC @_no_carry
    INC PPU_TargetAddr_U
  @_no_carry:
    DEC a:ZHV_GlyphIndex
    BNE @_chunk
    LDA #$00
    STA a:TextBox_DrawnLineNum              ; the new page starts on the top line
    RTS
